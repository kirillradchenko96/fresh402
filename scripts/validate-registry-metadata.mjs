import fs from 'node:fs';import assert from 'node:assert/strict';
const server=JSON.parse(fs.readFileSync(new URL('../server.json',import.meta.url)));
assert.equal(server.name,'io.github.kirillradchenko96/fresh402');
assert.equal(server.repository.url,'https://github.com/kirillradchenko96/fresh402');
assert.equal(server.repository.source,'github');
assert.deepEqual(server.remotes,[{type:'streamable-http',url:'https://api.fresh402.com/mcp'}]);
assert.equal(server.websiteUrl,'https://fresh402.com');
assert.ok(server.description.length<=100&&server.description.length>=10);
assert.match(server.version,/^\d+\.\d+\.\d+(?:\+metadata\.\d+)?$/,'Registry metadata uses API release plus an optional metadata revision');
const openapi=JSON.parse(fs.readFileSync(new URL('../docs/openapi.json',import.meta.url)));
assert.equal(server._meta?.['io.modelcontextprotocol.registry/publisher-provided']?.apiVersion??server.version,openapi.info.version,'Registry API release and reviewed documentation must match');
assert.deepEqual(server.icons,[{src:'https://fresh402.com/favicon.png',mimeType:'image/png',sizes:['256x256']},{src:'https://fresh402.com/favicon.svg',mimeType:'image/svg+xml',sizes:['any']}]);
assert.equal(Object.hasOwn(server,'packages'),false,'Hosted service, not the historical repository package');
console.log('Existing MCP namespace, repository, endpoint and production metadata validated.');
